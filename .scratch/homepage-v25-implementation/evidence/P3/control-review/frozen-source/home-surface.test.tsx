import { cleanup, fireEvent, render, screen, within, act } from "@testing-library/react";
import { useState } from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { createHomepageState, updateHomepageUi, type HomepageState } from "../../lib/reviews/homepage-v25-state";
import { buildInstrumentTradeSummaries } from "../../lib/trades/instruments";
import { buildTradeLibraryEntries } from "../../lib/trades/library";
import type { TradeExecution } from "../../lib/trades/types";
import { buildHomepageHoldings, type HomepageHolding } from "./holdings-model";
import { HomeSurface } from "./home-surface";

const scope = { live: true as const, market: "all" as const, accounts: ["*"], rangeMode: "all" as const };
const fills: TradeExecution[] = [{ id: "a", accountId: "one", accountLabel: "实盘一", source: { platform: "futu", row: 1, tradeNature: "live" }, instrument: { id: "CN-SH:600519", symbol: "600519", name: "贵州茅台", market: "CN-SH", currency: "CNY" }, side: "buy", executedAt: "2026-10-22T01:00:00Z", quantity: "2", price: "100", fee: "0" }];
const model = buildHomepageHoldings(buildTradeLibraryEntries(buildInstrumentTradeSummaries(fills), {}, {}), { scope, asOf: "2026-10-23" });
function Harness({ onTrades = vi.fn(), onImport = vi.fn(), holdings = model, accounts = [{ id: "one", label: "实盘一" }], initialUi }: { onTrades?: (row: HomepageHolding | null) => void; onImport?: () => void; holdings?: typeof model; accounts?: { id: string; label: string }[]; initialUi?: HomepageState }) {
  const [ui, setUi] = useState(() => initialUi ?? createHomepageState(scope));
  return <HomeSurface ui={ui} holdings={holdings} ready accountStatus="ready" accounts={accounts} onImport={onImport} onUi={patch => setUi(current => updateHomepageUi(current, patch))} onScope={vi.fn()} onTrades={onTrades} onReload={vi.fn()} onRepair={vi.fn()} />;
}
afterEach(() => { cleanup(); vi.useRealTimers(); });
describe("real homepage holding controls", () => {
  it("makes the surrounding navigation inert while detail owns focus and restores it on close", () => {
    render(<div className="homepage-v25-app"><aside className="app-sidebar" aria-label="主导航"><button type="button">交易库</button></aside><Harness /></div>);
    const navigation = screen.getByLabelText("主导航");
    fireEvent.click(screen.getByRole("button", { name: "查看持仓详情" }));
    expect(navigation).toHaveAttribute("inert");
    fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" });
    expect(navigation).not.toHaveAttribute("inert");
  });
  it("distinguishes unknown cost from missing quote in the actual table and detail", () => {
    const unknown = buildHomepageHoldings(buildTradeLibraryEntries(buildInstrumentTradeSummaries(fills.map(fill => ({ ...fill, source: { ...fill.source, historyIncomplete: ["statement gap"] } }))), {}, {}), { scope, asOf: "2026-10-23" });
    expect(unknown.rows[0].averageCost).toBeNull();
    expect(unknown.rows[0].quote).toBeNull();
    render(<Harness holdings={unknown} />);
    const table = screen.getByRole("table", { name: "当前持仓" });
    expect(within(table).getByText("暂无")).toBeInTheDocument();
    expect(within(table).getByText("待更新")).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "查看持仓详情" }));
    const dialog = screen.getByRole("dialog");
    expect(within(dialog).getByText("暂无")).toBeInTheDocument();
    expect(within(dialog).getByText("待更新")).toBeInTheDocument();
    const cost = within(dialog).getByRole("button", { name: "成本价完整值" });
    fireEvent.keyDown(cost, { key: "Enter" });
    expect(screen.getByRole("tooltip")).toHaveTextContent("暂无可信成本");
    fireEvent.keyDown(cost, { key: "Escape" });
    expect(screen.queryByRole("tooltip")).not.toBeInTheDocument();
    expect(dialog).toBeInTheDocument();
  });
  it("retains detail keyboard focus through a fresh row object and explains a removed row without clearing local UI", () => {
    const ui = updateHomepageUi(createHomepageState(scope), { holdings: { query: "茅台", sort: "name-desc", page: 1 } });
    const props = { ui, holdings: model, ready: true, accountStatus: "ready" as const, accounts: [{ id: "one", label: "实盘一" }], onUi: vi.fn(), onScope: vi.fn(), onTrades: vi.fn(), onReload: vi.fn(), onRepair: vi.fn(), onImport: vi.fn() };
    const { rerender } = render(<HomeSurface {...props} />);
    fireEvent.click(screen.getByRole("button", { name: "查看持仓详情" }));
    const forward = screen.getByRole("button", { name: "查看交易" }); forward.focus();
    rerender(<HomeSurface {...props} holdings={{ ...model, rows: model.rows.map(row => ({ ...row })) }} />);
    expect(forward).toHaveFocus();
    rerender(<HomeSurface {...props} holdings={{ ...model, rows: [] }} />);
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    expect(screen.getByText(/该持仓已变化/)).toBeInTheDocument();
    expect(screen.getByRole("heading", { name: "当前持仓（最新）" })).toHaveFocus();
    expect(screen.getByRole("searchbox", { name: "搜索持仓" })).toHaveValue("茅台");
  });
  it("keeps eight slots and a detail with one forward action; outside click stays open and Escape restores its exact trigger", () => {
    const onTrades = vi.fn();
    render(<Harness onTrades={onTrades} />);
    expect(screen.getAllByTestId("holding-slot")).toHaveLength(8);
    const trigger = screen.getByRole("button", { name: "查看持仓详情" });
    trigger.focus(); fireEvent.click(trigger);
    const dialog = screen.getByRole("dialog", { name: "贵州茅台 持仓详情" });
    expect(within(dialog).getByText("实盘一")).toBeInTheDocument();
    expect(within(dialog).getAllByRole("button", { name: "查看交易" })).toHaveLength(1);
    fireEvent.click(screen.getByTestId("holding-detail-backdrop"));
    expect(dialog).toBeInTheDocument();
    fireEvent.keyDown(dialog, { key: "Escape" });
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    expect(trigger).toHaveFocus();
    fireEvent.click(trigger); fireEvent.click(screen.getByRole("button", { name: "查看交易" }));
    expect(onTrades).toHaveBeenCalledWith(expect.objectContaining({ identity: "SSE:600519", accountId: "one" }));
  });
  it.each(["Escape", "close"])("restores focus only after the background and navigation leave inert (%s)", action => {
    render(<div className="homepage-v25-app"><aside className="app-sidebar" aria-label="主导航" /><Harness /></div>);
    const trigger = screen.getByRole("button", { name: "查看持仓详情" });
    fireEvent.click(trigger);
    const restoredStates: boolean[] = [];
    const originalFocus = trigger.focus.bind(trigger);
    vi.spyOn(trigger, "focus").mockImplementation(options => {
      restoredStates.push(Boolean(trigger.closest("[inert]")) || screen.getByLabelText("主导航").hasAttribute("inert"));
      originalFocus(options);
    });
    if (action === "Escape") fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" });
    else fireEvent.click(screen.getByRole("button", { name: "关闭持仓详情" }));
    expect(restoredStates).toEqual([false]);
    expect(trigger).toHaveFocus();
  });
  it("keeps the four core KPIs together and puts price, account and days in secondary information", () => {
    render(<Harness />);
    fireEvent.click(screen.getByRole("button", { name: "查看持仓详情" }));
    const dialog = screen.getByRole("dialog");
    const core = within(dialog).getByLabelText("核心持仓指标");
    expect(Array.from(core.children).map(card => card.querySelector("dt")?.textContent)).toEqual(["数量", "成本价(CNY)", "持仓市值(CNY)", "持仓浮动盈亏(CNY)"]);
    const secondary = within(dialog).getByLabelText("持仓补充信息");
    expect(within(secondary).getByText("最新价(CNY)")).toBeInTheDocument();
    expect(within(secondary).getByText("实盘一")).toBeInTheDocument();
    expect(within(secondary).getByText("持仓天数")).toBeInTheDocument();
  });
  it("returns to the exact non-default holding page through the visible source action without navigating", () => {
    const onTrades = vi.fn();
    const nine = { ...model, rows: Array.from({ length: 9 }, (_, index) => ({ ...model.rows[0], id: `holding-${index}`, instrumentName: `贵州茅台 ${index}` })) };
    const initialUi = updateHomepageUi(createHomepageState(scope), { holdings: { query: "贵州", sort: "name-desc", page: 2 }, scrollTop: 180 });
    render(<Harness holdings={nine} initialUi={initialUi} onTrades={onTrades} />);
    const trigger = screen.getByRole("button", { name: "查看持仓详情" });
    const holdingName = screen.getByRole("table", { name: "当前持仓" }).textContent;
    trigger.focus(); fireEvent.click(trigger);
    const dialog = screen.getByRole("dialog");
    expect(within(dialog).getAllByRole("button", { name: "查看交易" })).toHaveLength(1);
    fireEvent.click(within(dialog).getByRole("button", { name: "返回原持仓行第 2 页 · 恢复原滚动位置" }));
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    expect(trigger).toHaveFocus();
    expect(screen.getByRole("searchbox", { name: "搜索持仓" })).toHaveValue("贵州");
    expect(screen.getByRole("table", { name: "当前持仓" }).textContent).toBe(holdingName);
    expect(screen.getByText("2 / 2")).toBeInTheDocument();
    expect(onTrades).not.toHaveBeenCalled();
  });
  it("explains complete raw values with focus, Enter/Escape and synthetic pointer/click without false missing reasons", () => {
    const quote = { quoteDate: "2026-10-23", fetchedAt: "2026-10-23T08:00:00Z", provider: "tencent", currency: "CNY", price: "110.123456789", freshness: "current" as const };
    const entries = buildTradeLibraryEntries(buildInstrumentTradeSummaries(fills), {}, {});
    const known = buildHomepageHoldings(entries, { scope, asOf: "2026-10-23", quotesByInstrument: { "CN-SH:600519": quote }, candlesByInstrument: { "CN-SH:600519": [{ instrumentId: "CN-SH:600519", tradingDate: quote.quoteDate, open: quote.price, high: quote.price, low: quote.price, close: quote.price, volume: "1", currency: "CNY", provider: "tencent", providerSymbol: "600519", adjustmentMode: "raw", fetchedAt: quote.fetchedAt }] } });
    render(<Harness holdings={known} />);
    fireEvent.click(screen.getByRole("button", { name: "查看持仓详情" }));
    const dialog = screen.getByRole("dialog");
    const cost = within(dialog).getByRole("button", { name: "成本价完整值" });
    fireEvent.focus(cost);
    expect(screen.getByRole("tooltip")).toHaveTextContent("100");
    expect(screen.getByRole("tooltip")).not.toHaveTextContent("暂无");
    fireEvent.keyDown(cost, { key: "Enter" });
    fireEvent.keyDown(cost, { key: "Escape" });
    expect(screen.queryByRole("tooltip")).not.toBeInTheDocument();
    expect(dialog).toBeInTheDocument();
    const price = within(dialog).getByRole("button", { name: "最新价完整值" });
    fireEvent.pointerDown(price, { pointerType: "touch" }); fireEvent.click(price);
    expect(screen.getByRole("tooltip")).toHaveTextContent("110.123456789");
    expect(screen.getByRole("tooltip")).not.toHaveTextContent("待更新");
    fireEvent.pointerDown(dialog);
    expect(screen.queryByRole("tooltip")).not.toBeInTheDocument();
    fireEvent.mouseEnter(price);
    expect(screen.getByRole("tooltip")).toHaveTextContent("110.123456789");
    fireEvent.mouseLeave(price);
    expect(screen.queryByRole("tooltip")).not.toBeInTheDocument();
  });
  it("offers import for an empty account menu and a truly empty holding set, without a duplicate no-match action", async () => {
    const onImport = vi.fn();
    const empty = { ...model, rows: [], totalMarketValue: null, totalUnrealizedPnl: null };
    render(<Harness holdings={empty} accounts={[]} onImport={onImport} />);
    fireEvent.click(screen.getByRole("button", { name: "导入交易" }));
    expect(onImport).toHaveBeenCalledTimes(1);
    fireEvent.click(screen.getByRole("button", { name: "全部账户" }));
    fireEvent.click(screen.getByRole("button", { name: "导入账户" }));
    expect(onImport).toHaveBeenCalledTimes(2);
    cleanup(); vi.useFakeTimers();
    render(<Harness holdings={model} onImport={onImport} />);
    fireEvent.click(screen.getByRole("button", { name: "搜索持仓" }));
    fireEvent.change(screen.getByRole("searchbox"), { target: { value: "无匹配" } });
    await act(() => vi.advanceTimersByTimeAsync(300));
    expect(screen.getByText("没有匹配的持仓")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "导入交易" })).not.toBeInTheDocument();
    expect(screen.getAllByRole("button", { name: "清除持仓搜索" })).toHaveLength(1);
  });
  it("does not query during IME composition and applies the inline search after 300 ms", async () => {
    vi.useFakeTimers(); render(<Harness />);
    fireEvent.click(screen.getByRole("button", { name: "搜索持仓" }));
    const input = screen.getByRole("searchbox", { name: "搜索持仓" });
    fireEvent.compositionStart(input); fireEvent.change(input, { target: { value: "不存在" } });
    await act(() => vi.advanceTimersByTimeAsync(350));
    expect(screen.getByRole("button", { name: "查看持仓详情" })).toBeInTheDocument();
    fireEvent.compositionEnd(input); await act(() => vi.advanceTimersByTimeAsync(299));
    expect(screen.getByRole("button", { name: "查看持仓详情" })).toBeInTheDocument();
    await act(() => vi.advanceTimersByTimeAsync(1));
    expect(screen.queryByRole("button", { name: "查看持仓详情" })).not.toBeInTheDocument();
    expect(screen.getByText("没有匹配的持仓")).toBeInTheDocument();
    expect(screen.getAllByTestId("holding-slot")).toHaveLength(8);
  });
});
